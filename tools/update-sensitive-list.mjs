// Rebuilds extension/data/sensitive-sites.js from the South Korea blocked-sites list.
//
//   node tools/update-sensitive-list.mjs              # download the latest list
//   node tools/update-sensitive-list.mjs path/to/kr.list
//
// Pages on these domains (or proxies to them) are never described to the AI judge.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SOURCE = 'https://github.com/wpzzz/blocked-sites-in-south-korea/blob/main/kr.list';
const RAW = 'https://raw.githubusercontent.com/wpzzz/blocked-sites-in-south-korea/main/kr.list';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'extension', 'data', 'sensitive-sites.js');
const DOMAIN = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

async function readSource() {
  const file = process.argv[2];
  if (file) return readFileSync(file, 'utf8');
  const res = await fetch(RAW);
  if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
  return res.text();
}

const text = await readSource();
const domains = [
  ...new Set(
    text
      .split(/\r?\n/)
      .map((l) => l.trim().toLowerCase().replace(/^\*\./, '').replace(/^www\./, ''))
      .filter((l) => l && !l.startsWith('#') && DOMAIN.test(l)),
  ),
].sort();

if (domains.length < 100) throw new Error(`Only ${domains.length} domains parsed; refusing to overwrite.`);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// Generated by tools/update-sensitive-list.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: ${SOURCE}
// ${domains.length} domains. Pages on these sites, or proxies to them, are never described to the AI judge.
export const SENSITIVE_DOMAINS = ${JSON.stringify(domains)};
`,
);
console.log(`wrote ${domains.length} domains to ${OUT}`);
